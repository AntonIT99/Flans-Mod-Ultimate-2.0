package com.flansmodultimate.util;

import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.nio.ByteBuffer;
import java.nio.ByteOrder;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.OptionalInt;

import static org.junit.jupiter.api.Assertions.*;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

class SoundLengthIndexTest
{
    /** One of the packs bundled in this repository, whose index is generated by the Python script. */
    private static final Path BUNDLED_PACK_ASSETS = Path.of("src", "officialpacks", "resources", "assets", "flansmod");

    private static final int SAMPLE_RATE = 44100;

    @TempDir
    Path tempDir;

    @BeforeEach
    void forgetSoundsLoadedByEarlierTests()
    {
        SoundLengthIndex.clear();
    }

    /** Writes a pack holding a single sound and returns its generated index. */
    private Path generateIndex(String packName, String soundFileName, long totalSamples) throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve(packName).resolve("sounds"));
        writeOggFile(soundsDir.resolve(soundFileName), totalSamples);

        Path indexFile = soundsDir.resolveSibling(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);
        return indexFile;
    }

    @Test
    void indexesEverySoundWithItsEventKeyAndLength() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("sounds"));
        writeOggFile(soundsDir.resolve("Engine Start.ogg"), SAMPLE_RATE * 2L);
        writeOggFile(soundsDir.resolve("nested").resolve("idle.ogg"), SAMPLE_RATE * 3L);

        Path indexFile = tempDir.resolve(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);

        JsonObject sounds = readIndex(indexFile).getAsJsonObject("sounds");
        assertEquals(2, sounds.size());
        assertEquals("engine_start", sounds.getAsJsonObject("Engine Start.ogg").get("key").getAsString());
        assertEquals(40, sounds.getAsJsonObject("Engine Start.ogg").get("ticks").getAsInt());
        assertEquals("idle", sounds.getAsJsonObject("nested/idle.ogg").get("key").getAsString());
        assertEquals(60, sounds.getAsJsonObject("nested/idle.ogg").get("ticks").getAsInt());
    }

    @Test
    void recordsUnreadableSoundsSoTheyDoNotForceAnEndlessRescan() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("sounds"));
        Files.write(soundsDir.resolve("broken.ogg"), "not a sound".getBytes(StandardCharsets.UTF_8));

        Path indexFile = tempDir.resolve(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);

        assertEquals(0, readIndex(indexFile).getAsJsonObject("sounds").getAsJsonObject("broken.ogg").get("ticks").getAsInt());
        assertFalse(SoundLengthIndex.isOutdated(soundsDir, indexFile));
    }

    @Test
    void aFreshlyGeneratedIndexIsUpToDate() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("sounds"));
        writeOggFile(soundsDir.resolve("shoot.ogg"), SAMPLE_RATE);

        Path indexFile = tempDir.resolve(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);

        assertFalse(SoundLengthIndex.isOutdated(soundsDir, indexFile));
    }

    @Test
    void aMissingIndexIsOutdatedOnlyWhenThePackHasSounds() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("sounds"));
        Path indexFile = tempDir.resolve(SoundLengthIndex.FILE_NAME);

        assertFalse(SoundLengthIndex.isOutdated(soundsDir, indexFile));
        assertFalse(SoundLengthIndex.isOutdated(tempDir.resolve("absent"), indexFile));

        writeOggFile(soundsDir.resolve("shoot.ogg"), SAMPLE_RATE);
        assertTrue(SoundLengthIndex.isOutdated(soundsDir, indexFile));
    }

    @Test
    void addedRemovedAndReplacedSoundsMakeTheIndexOutdated() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("sounds"));
        Path shoot = soundsDir.resolve("shoot.ogg");
        writeOggFile(shoot, SAMPLE_RATE);

        Path indexFile = tempDir.resolve(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);

        Path reload = soundsDir.resolve("reload.ogg");
        writeOggFile(reload, SAMPLE_RATE);
        assertTrue(SoundLengthIndex.isOutdated(soundsDir, indexFile));

        Files.delete(reload);
        assertFalse(SoundLengthIndex.isOutdated(soundsDir, indexFile));

        writeOggFile(shoot, SAMPLE_RATE * 4L, 1);
        assertTrue(SoundLengthIndex.isOutdated(soundsDir, indexFile));

        Files.delete(shoot);
        assertTrue(SoundLengthIndex.isOutdated(soundsDir, indexFile));
    }

    @Test
    void anIndexWrittenInAnOlderFormatIsOutdated() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("sounds"));
        writeOggFile(soundsDir.resolve("shoot.ogg"), SAMPLE_RATE);

        Path indexFile = tempDir.resolve(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);
        Files.writeString(indexFile, Files.readString(indexFile).replaceFirst("\"version\": \\d+", "\"version\": 0"));

        assertTrue(SoundLengthIndex.isOutdated(soundsDir, indexFile));
    }

    @Test
    void theIndexRemovesItselfWhenThePackHasNoSounds() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("sounds"));
        Path shoot = soundsDir.resolve("shoot.ogg");
        writeOggFile(shoot, SAMPLE_RATE);

        Path indexFile = tempDir.resolve(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);
        Files.delete(shoot);
        SoundLengthIndex.generate(soundsDir, indexFile);

        assertFalse(Files.exists(indexFile));
        assertFalse(SoundLengthIndex.isOutdated(soundsDir, indexFile));
    }

    @Test
    void loadedSoundsCanBeLookedUpByTheNameAContentPackConfigures() throws IOException
    {
        Path indexFile = generateIndex("pack", "Engine Start.ogg", SAMPLE_RATE * 2L);
        SoundLengthIndex.load(indexFile);

        // Content packs configure sounds in any spelling, so the lookup sanitizes them the same way the index does.
        assertEquals(OptionalInt.of(40), SoundLengthIndex.getSoundLength("engine_start"));
        assertEquals(OptionalInt.of(40), SoundLengthIndex.getSoundLength("Engine Start"));
        assertTrue(SoundLengthIndex.getSoundLength("unknown_sound").isEmpty());
    }

    @Test
    void theFirstPackProvidingASoundOwnsItsLength() throws IOException
    {
        Path firstPack = generateIndex("first", "shoot.ogg", SAMPLE_RATE);
        Path secondPack = generateIndex("second", "shoot.ogg", SAMPLE_RATE * 3L);

        SoundLengthIndex.load(firstPack);
        SoundLengthIndex.load(secondPack);

        assertEquals(OptionalInt.of(20), SoundLengthIndex.getSoundLength("shoot"));
    }

    @Test
    void soundsThatCouldNotBeMeasuredAreNotLookedUp() throws IOException
    {
        Path soundsDir = Files.createDirectories(tempDir.resolve("broken").resolve("sounds"));
        Files.write(soundsDir.resolve("broken.ogg"), "not a sound".getBytes(StandardCharsets.UTF_8));

        Path indexFile = soundsDir.resolveSibling(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(soundsDir, indexFile);
        SoundLengthIndex.load(indexFile);

        assertTrue(SoundLengthIndex.getSoundLength("broken").isEmpty());
    }

    @Test
    void loadingAnAbsentIndexChangesNothing()
    {
        SoundLengthIndex.load(tempDir.resolve("absent.json"));

        assertTrue(SoundLengthIndex.getSoundLength("shoot").isEmpty());
    }

    /**
     * The indexes of the bundled packs are generated by scripts/buildSoundLengthIndexes.py, so both
     * implementations have to measure and name every sound identically.
     */
    @Test
    void matchesTheIndexGeneratedForTheBundledPacks() throws IOException
    {
        Path bundledIndex = BUNDLED_PACK_ASSETS.resolve(SoundLengthIndex.FILE_NAME);
        assumeTrue(Files.isRegularFile(bundledIndex), "Bundled pack assets are not available");

        Path regeneratedIndex = tempDir.resolve(SoundLengthIndex.FILE_NAME);
        SoundLengthIndex.generate(BUNDLED_PACK_ASSETS.resolve("sounds"), regeneratedIndex);

        assertEquals(readIndex(bundledIndex), readIndex(regeneratedIndex));
    }

    private static JsonObject readIndex(Path indexFile) throws IOException
    {
        return JsonParser.parseString(Files.readString(indexFile, StandardCharsets.UTF_8)).getAsJsonObject();
    }

    private static void writeOggFile(Path file, long totalSamples) throws IOException
    {
        writeOggFile(file, totalSamples, 0);
    }

    /**
     * Writes a minimal Ogg Vorbis stream: an identification page, any number of audio pages, and a
     * page ending the stream. The audio pages only exist to give the file a distinct size.
     */
    private static void writeOggFile(Path file, long totalSamples, int audioPages) throws IOException
    {
        Files.createDirectories(file.getParent());

        ByteBuffer identification = ByteBuffer.allocate(30).order(ByteOrder.LITTLE_ENDIAN);
        identification.put((byte)0x01);
        identification.put("vorbis".getBytes(StandardCharsets.UTF_8));
        identification.putInt(0);
        identification.put((byte)2);
        identification.putInt(SAMPLE_RATE);
        identification.putInt(0);
        identification.putInt(128000);
        identification.putInt(0);
        identification.put((byte)0xB8);
        identification.put((byte)0x01);

        ByteArrayOutputStream content = new ByteArrayOutputStream();
        content.writeBytes(page(0L, identification.array()));
        for (int audioPage = 0; audioPage < audioPages; audioPage++)
            content.writeBytes(page(0L, new byte[64]));
        content.writeBytes(page(totalSamples, new byte[0]));

        Files.write(file, content.toByteArray());
    }

    private static byte[] page(long granulePosition, byte[] payload)
    {
        int segmentCount = Math.max(1, (payload.length + 254) / 255);

        ByteBuffer page = ByteBuffer.allocate(27 + segmentCount + payload.length).order(ByteOrder.LITTLE_ENDIAN);
        page.put("OggS".getBytes(StandardCharsets.UTF_8));
        page.put((byte)0);
        page.put((byte)0);
        page.putLong(granulePosition);
        page.putInt(1);
        page.putInt(0);
        page.putInt(0);
        page.put((byte)segmentCount);

        int remaining = payload.length;
        for (int segment = 0; segment < segmentCount; segment++)
        {
            page.put((byte)Math.min(255, remaining));
            remaining -= Math.min(255, remaining);
        }
        page.put(payload);

        return page.array();
    }
}
